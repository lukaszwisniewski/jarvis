from app.slack.formatting import format_response


def test_format_response_structure():
    result = format_response(
        query="how does thumbnail generation work?",
        answer="Thumbnails are generated by the media service.",
        user_id="U12345",
    )

    assert result["response_type"] == "ephemeral"

    assert "blocks" in result
    assert isinstance(result["blocks"], list)
    blocks_text = str(result["blocks"])
    assert "<@U12345>" in blocks_text


def test_format_response_contains_query_and_answer():
    result = format_response(
        query="what is the upload limit?",
        answer="The upload limit is 500MB.",
        user_id="U99999",
    )

    blocks_text = str(result["blocks"])

    assert "what is the upload limit?" in blocks_text
    assert "The upload limit is 500MB." in blocks_text
    assert "<@U99999>" in blocks_text
